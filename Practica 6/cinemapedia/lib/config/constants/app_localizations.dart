  static String getAgeRating(double voteAverage, String langCode) {
    if (voteAverage <= 0.0) return 'NR';
    switch (langCode) {
      case 'es': // México / Latinoamérica
        if (voteAverage >= 8.5) return 'AA';
        if (voteAverage >= 7.0) return 'A';
        if (voteAverage >= 5.5) return 'B';
        if (voteAverage >= 4.0) return 'B15';
        return 'C';
      case 'en': // Estados Unidos
        if (voteAverage >= 8.5) return 'G';
        if (voteAverage >= 7.0) return 'PG';
        if (voteAverage >= 5.5) return 'PG-13';
        if (voteAverage >= 4.0) return 'R';
        return 'NC-17';
      case 'de': // Alemania (FSK)
        if (voteAverage >= 8.5) return 'FSK 0';
        if (voteAverage >= 7.0) return 'FSK 6';
        if (voteAverage >= 5.5) return 'FSK 12';
        if (voteAverage >= 4.0) return 'FSK 16';
        return 'FSK 18';
      case 'zh': // China / Taiwán
        if (voteAverage >= 8.0) return '普遍级';
        if (voteAverage >= 6.5) return '保护级';
        if (voteAverage >= 5.0) return '辅导级';
        return '限制级';
      case 'ar': // Países Árabes
        if (voteAverage >= 8.5) return 'G';
        if (voteAverage >= 7.0) return 'PG';
        if (voteAverage >= 5.5) return 'PG12';
        if (voteAverage >= 4.0) return '15+';
        return '18+';
      default:
        return 'NR';
    }
  }
